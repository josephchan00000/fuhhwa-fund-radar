NAMES = {"E0": "名單出來下一個交易日開盤買（現在）", "E1": "開低才買", "E2": "拉回 10 日線下才買", "E3": "創 20 日新高才買",
         "E4": "一半現在買、一半拉回才買", "E0r": "下一個交易日開盤買、買不到不遞補"}


def window(e: str) -> int:
    """名單後最晚第幾個交易日開盤還能買（E1：第 5 天；E2、E3：條件看到第 10 天、隔天第 11 天開盤；E0r：第 1 天）。"""
    return {"E0r": 1, "E1": E1_DAYS, "E2": E2_DAYS + 1, "E3": E3_DAYS + 1}[e]


def pick(runs: dict) -> str | None:
    """runs＝{進場: {"cagr": {"all","h1","h2"}, "mdd": {"all","h1"}}} → 2019–2022 挑出來的那一種。"""
    base = runs["E0"]
    ok = [e for e in ENTRY if e in runs and runs[e]["mdd"]["h1"] <= base["mdd"]["h1"] + PASS["mdd_pick"] / 100]
    if not ok:
        return None
    best = max(runs[e]["cagr"]["h1"] for e in ok)
    return next(e for e in ok if runs[e]["cagr"]["h1"] == best)


def verdict(runs: dict) -> tuple[str, str | None]:
    e = pick(runs)
    if e is None or e == "E0":
        return "不換", e
    a, b = runs[e], runs["E0"]
    better = all(a["cagr"][k] > b["cagr"][k] for k in ("all", "h1", "h2"))
    dd_ok = a["mdd"]["all"] <= b["mdd"]["all"] + PASS["mdd_extra"] / 100
    return ("換" if better and dd_ok else "不換"), e
