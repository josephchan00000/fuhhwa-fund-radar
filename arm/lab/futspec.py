DECIDE_S = 8 * 3600 + 59 * 60 + 30   # 08:59:30
EXIT_S = 13 * 3600 + 44 * 60         # 13:44:00
REF_S = 13 * 3600 + 30 * 60          # 前一天 13:30:00 的期貨價（含）以前最後一筆
COVER_MIN = 0.95                     # 偷看版：開盤價找得到的比重合計至少 95%

VERSIONS = ("lookahead", "realtime")
RT_FIELD = "pz"                      # 證交所 MIS 的試撮價
