RT_COVER_MIN = 0.80                  # 用到的股票比重合計至少 80%
RT_SAMPLE = {"top_n": 150, "batch": 50, "per_tick": 2, "step": 5,
             "start_s": 8 * 3600 + 58 * 60, "end_s": 9 * 3600 + 15}   # 取樣方式（arm/lab/futpre.py 要一致）
REALTIME = {"field": RT_FIELD, "recv_le": "DECIDE_S", "pick": "latest_data_time", "fresh_s": RT_FRESH_S,
            "base": "prev_official_close", "weights": "futsig.weights", "cover_min": RT_COVER_MIN}

TH_WINDOW = 20
TH_MIN_HIST = 10
TH_TOP_PCT = 45                      # 前 45%（用整數百分比，避免 1 − 0.45 的浮點誤差讓位置少一格）

SCALE_BASE = 23919.0                 # 2025 年加權指數平均（data/lab/heat/taiex 的 2025 年收盤平均）
POINTS = {"stop": 10, "buf": 2, "clear": 20, "target": 60}   # 作者的點數（換算前）
SLIP = 1

TAX = 0.00002                        # 期交稅每邊 0.002%（契約價值）；換成點數＝TAX × 價格
FEE_NTD = 60                         # 手續費每邊（大台）

JUDGE = {"days": 60, "min_trades": 30, "placebo_n": 1000, "placebo_p": 0.05}
SEED = 20261027
COMPARE = ("raw_points", "always_long", "always_short", "est_err")   # est_err：VER 2，即時版估算 − 偷看版開盤水準


def scale(i_prev: float) -> float:
    return i_prev / SCALE_BASE


def points(i_prev: float, raw: bool = False) -> dict[str, int]:
    """當天要用的點數：作者點數 × 前一天收盤指數 ÷ SCALE_BASE，四捨五入到整數點（raw＝作者原點數）。"""
    k = 1.0 if raw else scale(i_prev)
    return {key: int(round(v * k)) for key, v in POINTS.items()}


def cost_side(price: float) -> float:
    """每邊成本（點）。"""
    return TAX * price + FEE_NTD / POINT_NTD


def threshold(past_abs: list[float]) -> float | None:
    """過去 |E|（最多 TH_WINDOW 個、時間順序）→ 門檻；不到 TH_MIN_HIST 個回 None（不做）。"""
    xs = sorted(past_abs[-TH_WINDOW:])
    if len(xs) < TH_MIN_HIST:
        return None
    return xs[len(xs) * (100 - TH_TOP_PCT) // 100]
