def alpha(w: float) -> float:
    return 2.0 / (w + 1.0)


def span_nb(w: int, f: float) -> int:
    """只描述用的 EMA 天數：w × f 四捨五入（5 → 4、6；20 → 16、24；60 → 48、72）。"""
    return int(w * f + 0.5)


def better(me: float | None, ms: float | None, lo: float | None, pe: float | None, ps: float | None) -> bool:
    """第 4 點：E 的 o 平均 me 比 ms 高、差的 95% 區間下限 lo > 0、o > 0 的比例 pe ≥ ps，三個都成立才換。"""
    if None in (me, ms, lo, pe, ps):
        return False
    return me > ms and lo > 0 and pe >= ps
