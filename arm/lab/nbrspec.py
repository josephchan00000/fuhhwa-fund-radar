def dim_ok(rs: list[tuple[int, float | None, float | None]], n_min: int, edge: float, same: bool = False) -> bool | None:
    """一個維度的鄰近 [(次數, 命中率, 平常)…] → True 穩定／False 不穩定／None 看不出來（能用的一個都沒有，或 same：鄰近都和原本一樣）。"""
    if same:
        return None
    use = [(n, h, b) for n, h, b in rs if n >= n_min and h is not None and b is not None]
    if not use:
        return None
    ok = sum(1 for _, h, b in use if h - b >= edge)
    return ok * 2 >= len(use)


def overall(dims: dict[str, bool | None]) -> bool | None:
    """各維度 → 穩定 True／只在這個參數成立 False／看不出來 None。"""
    vs = [v for v in dims.values() if v is not None]
    if not vs:
        return None
    return all(vs)
