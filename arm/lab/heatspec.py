def use(values: dict):
    """暫時把這個模組的規格換成 values（美股：heatspec_us.spec_for(指數)），離開時換回來。
    景氣模組都在執行時讀 heatspec 的常數，所以換上去就是那個市場的規格；當成函式預設參數的常數兩邊必須一樣（tests 守）。"""
    from contextlib import contextmanager

    @contextmanager
    def _cm():
        g = globals()
        old = {k: g[k] for k in values if k in g}
        added = [k for k in values if k not in g]
        g.update(values)
        try:
            yield
        finally:
            g.update(old)
            for k in added:
                g.pop(k, None)
    return _cm()


def band(x: float | None) -> str | None:
    if x is None:
        return None
    for lo, hi, nm in BANDS:
        if lo <= x < hi:
            return nm
    return None
