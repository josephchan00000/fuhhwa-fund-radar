def lag_years(n: int) -> int:
    """要等幾年才知道過去的訊號中了沒有：半年以內 0 年，其他＝ceil(n ÷ 252)。"""
    return 0 if n <= 126 else math.ceil(n / 252)


def first_year(book: str) -> int:
    return FIRST_YEAR + lag_years(BOOKS[book]["n"])


def folds(book: str) -> tuple[int, ...]:
    return tuple(range(first_year(book), LAST_FOLD + 1))


def fold_periods(y: int, book: str) -> dict:
    """交易年 y 的 IS、子期間、VAL、交易期間（日期字串）。VAL 另外只留「訊號日索引＋n ≤ (y−1) 年最後一個交易日的索引」的樣本。"""
    from datetime import date
    L = lag_years(BOOKS[book]["n"])
    v0, v1 = y - L - VAL_YEARS, y - 1 - L
    is_end = f"{v0 - 1}-12-31"
    a, b = date.fromisoformat(IS_START), date.fromisoformat(is_end)
    mid = date.fromordinal(a.toordinal() + (b.toordinal() - a.toordinal()) // 2)
    nxt = date.fromordinal(mid.toordinal() + 1)
    return {"is": (IS_START, is_end), "subs": ((IS_START, mid.isoformat()), (nxt.isoformat(), is_end)),
            "val": (f"{v0}-01-01", f"{v1}-12-31"), "trade": (f"{y}-01-01", f"{y}-12-31"), "known": f"{y - 1}-12-31"}


